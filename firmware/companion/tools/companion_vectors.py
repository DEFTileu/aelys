#!/usr/bin/env python3
"""Generate the companion identity test vectors (deterministic; fixed TEST keys, never real secrets).

Writes, from the repo root of this script's checkout:
  firmware/companion/sim/vectors.h                            (C arrays for the host test and the board self-test)
  apps/web/src/tests/fixtures/companion-vectors.json          (same values for the web test)
Both outputs are GENERATED by this script: re-run it, never edit them by hand.

  .venv/bin/python -I firmware/companion/tools/companion_vectors.py             # regenerate
  .venv/bin/python -I firmware/companion/tools/companion_vectors.py --verify-sig <b64url>
      checks a board signature over the vector login message with the backend verify_signature.

SAS and the signature check call backend/app/core/device_auth.py directly (read only).
"""
import argparse
import base64
import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve()
COMPANION = HERE.parent.parent
REPO = COMPANION.parent.parent

# The backend settings object demands a secret at import time; this is a harmless dummy, never a real key.
os.environ.setdefault("AELYS_SECRET_KEY", "companion-vectors-dummy-not-a-secret-0000")
sys.path.insert(0, str(REPO / "backend"))
from app.core.device_auth import sas_code, verify_signature  # noqa: E402

from cryptography.hazmat.primitives import hashes, serialization  # noqa: E402
from cryptography.hazmat.primitives.asymmetric import ec  # noqa: E402
from cryptography.hazmat.primitives.ciphers.aead import AESGCM  # noqa: E402
from cryptography.hazmat.primitives.kdf.hkdf import HKDF  # noqa: E402

DEVICE_PRIV = bytes.fromhex("0b7d3a5c1e9f4a2d8c6b0e1f3a5d7c9b2e4f6a8c0d1b3e5f7a9c1d3e5f7a9b11")
EPH_PRIV = bytes.fromhex("5f3c9a1d7b2e4c6a8d0f1b3e5a7c9d2f4b6e8a0c1d3f5b7e9a1c3d5f7b9d1e22")
NONCE = bytes.fromhex("a1b2c3d4e5f60718293a4b5c")
DEVICE_ID = "7b0e5c3a-4d21-4f6b-9a38-2c1d5e8f0a64"
WRONG_DEVICE_ID = "00000000-0000-4000-8000-000000000000"
SECRET = "test-pairing-secret-0123456789abcdef-not-real"
PAIRING_ID = "9f2c4e6a-1b3d-4857-a0c2-e4f6a8b0d2c4"
SSID = 'Café Ж"\\'
PASSWORD = "p@ss word 12345"
LOGIN_NONCE = "dGVzdC1sb2dpbi1ub25jZS0wMTIzNDU2Nzg5"  # fixed challenge nonce for the signature self-test


def b64u(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()


def point(priv: ec.EllipticCurvePrivateKey) -> bytes:
    return priv.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)


def login_message() -> bytes:
    return f"aelys-device-login-v1\n{DEVICE_ID}\n{LOGIN_NONCE}".encode()


def build():
    dev = ec.derive_private_key(int.from_bytes(DEVICE_PRIV, "big"), ec.SECP256R1())
    eph = ec.derive_private_key(int.from_bytes(EPH_PRIV, "big"), ec.SECP256R1())
    dev_pub, eph_pub = point(dev), point(eph)
    ssid, pw = SSID.encode(), PASSWORD.encode()
    plain = bytes([len(ssid)]) + ssid + bytes([len(pw)]) + pw
    z = eph.exchange(ec.ECDH(), dev.public_key())
    key = HKDF(algorithm=hashes.SHA256(), length=32, salt=eph_pub + dev_pub, info=b"aelys-wifi-v1").derive(z)

    def blob(aad: str) -> bytes:
        return b"\x01" + eph_pub + NONCE + AESGCM(key).encrypt(NONCE, plain, aad.encode())

    good, bad = blob(DEVICE_ID), blob(WRONG_DEVICE_ID)
    assert len(good) <= 192
    return {
        "device_priv": DEVICE_PRIV, "device_pub": dev_pub, "eph_pub": eph_pub, "plain": plain,
        "blob": good, "blob_wrong_aad": bad, "sas": sas_code(SECRET, PAIRING_ID, b64u(dev_pub)),
    }


def c_str(b: bytes) -> str:
    return '"' + "".join(chr(c) if 32 <= c < 127 and chr(c) not in '"\\?' else f"\\{c:03o}" for c in b) + '"'


def c_arr(name: str, b: bytes) -> str:
    rows = [", ".join(f"0x{x:02x}" for x in b[i:i + 12]) for i in range(0, len(b), 12)]
    return f"__attribute__((unused)) static const uint8_t {name}[] = {{\n    " + ",\n    ".join(rows) + f",\n}};\n#define {name}_LEN {len(b)}\n"


def write_header(v, path: Path):
    parts = [
        "/* GENERATED by firmware/companion/tools/companion_vectors.py: do not edit. TEST keys only, never real secrets. */\n"
        "#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n",
        c_arr("VEC_DEVICE_PRIV", v["device_priv"]), c_arr("VEC_DEVICE_PUB", v["device_pub"]),
        c_arr("VEC_BLOB", v["blob"]), c_arr("VEC_BLOB_WRONG_AAD", v["blob_wrong_aad"]),
        f"__attribute__((unused)) static const char VEC_DEVICE_ID[] = {c_str(DEVICE_ID.encode())};\n",
        f"__attribute__((unused)) static const char VEC_SECRET[] = {c_str(SECRET.encode())};\n",
        f"__attribute__((unused)) static const char VEC_PAIRING_ID[] = {c_str(PAIRING_ID.encode())};\n",
        f"__attribute__((unused)) static const char VEC_SAS[] = {c_str(v['sas'].encode())};\n",
        f"__attribute__((unused)) static const char VEC_SSID[] = {c_str(SSID.encode())};\n",
        f"__attribute__((unused)) static const char VEC_PASS[] = {c_str(PASSWORD.encode())};\n",
        f"__attribute__((unused)) static const char VEC_LOGIN_MSG[] = {c_str(login_message())};\n",
    ]
    path.write_text("".join(parts))


def write_json(v, path: Path):
    n = len(v["eph_pub"])
    assert n == 65
    d = {
        "_generated": "by firmware/companion/tools/companion_vectors.py; do not edit",
        "device_id": DEVICE_ID, "device_pub_b64": b64u(v["device_pub"]),
        "secret": SECRET, "pairing_id": PAIRING_ID, "sas": v["sas"],
        "ssid": SSID, "password": PASSWORD,
        "eph_jwk": {"kty": "EC", "crv": "P-256", "d": b64u(EPH_PRIV), "x": b64u(v["eph_pub"][1:33]), "y": b64u(v["eph_pub"][33:])},
        "nonce_b64": b64u(NONCE), "blob_b64": b64u(v["blob"]),
        "wrong_aad_device_id": WRONG_DEVICE_ID, "wrong_aad_blob_b64": b64u(v["blob_wrong_aad"]),
        "login_message": login_message().decode(),
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(d, indent=2, ensure_ascii=False) + "\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--verify-sig", metavar="B64URL")
    a = ap.parse_args()
    v = build()
    if a.verify_sig:
        ok = verify_signature(b64u(v["device_pub"]), login_message(), a.verify_sig.strip())
        print("OK" if ok else "FAIL")
        return 0 if ok else 1
    write_header(v, COMPANION / "sim" / "vectors.h")
    write_json(v, REPO / "apps/web/src/tests/fixtures/companion-vectors.json")
    print("sas", v["sas"], "blob bytes", len(v["blob"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
